def main_projection(obj: Any) -> Any:
    # Only the family worker emits timing fields, directly on its row objects.
    if isinstance(obj, dict) and obj.get('schema')=='codeprobe-a18-results/1':
        value=copy.deepcopy(obj)
        for row in value['rows']:
            if 'elapsed_seconds' not in row:
                raise Refusal('missing A18 row timing')
            del row['elapsed_seconds']
        return value
    if not isinstance(obj, list):
        return copy.deepcopy(obj)
    rows = []
    for row in obj:
        if not isinstance(row, dict):
            raise Refusal('non-record family result')
        if not {'cell_id','side','arm','start_utc','elapsed_seconds'} <= set(row):
            raise Refusal('incomplete family record/timing schema')
        rows.append({k:v for k,v in row.items() if k not in ('start_utc','elapsed_seconds')})
    return rows

def red_projection(obj: dict) -> dict:
    result = copy.deepcopy(obj)
    controls = result.get('negative_controls')
    if not isinstance(controls,list):
        raise Refusal('missing negative controls')
    named = [r for r in controls if str(r.get('id','')).startswith('INVALID_VALUE-')]
    others = [r for r in controls if not str(r.get('id','')).startswith('INVALID_VALUE-')]
    if len(named)!=4 or {r['id'] for r in named}!={f'INVALID_VALUE-{i}' for i in range(4)}:
        raise Refusal('wrong positional control inventory')
    states = {r.get('state') for r in named}
    if len(states)!=4 or states!={'observed','unavailable','not_applicable','insufficient_evidence'}:
        raise Refusal('wrong or duplicated state-keyed control inventory')
    result['negative_controls'] = others + [dict(r, id='INVALID_VALUE-state:'+r['state']) for r in sorted(named,key=lambda r:r['state'])]
    return result

def compare_references(root: Path, outputs: Path) -> dict:
    references=root/'experiments/p7c/reference'; rows=[]
    for p in sorted(references.glob('*.json')):
        current=read(outputs/p.name); expected=read(p)
        raw_equal=expected==current
        if p.name=='redteam.json':
            eq=red_projection(expected)==red_projection(current)
            rule='Only the four INVALID_VALUE positional IDs are keyed by state; other fields compare exactly.'
        else:
            eq=main_projection(expected)==main_projection(current)
            rule='Only direct family-row start_utc/elapsed_seconds and A18 rows/*/elapsed_seconds are excluded; all other fields compare exactly.'
        rows.append({'file':p.name,'equal':eq,'raw_json_equal':raw_equal,'rule':rule,
                     'reference_sha256':sha(p),'observed_sha256':sha(outputs/p.name)})
    if len(rows)!=18 or not all(x['equal'] for x in rows):
        raise Refusal('reference disagreement retained: '+str([x['file'] for x in rows if not x['equal']]))
    return {'schema':'codeprobe-p7d-reference-comparison/1','main_files':17,'supplemental_files':1,
            'all_equal_in_declared_comparison':True,'raw_files_rewritten':False,'files':rows}

def require_pilot(p: dict) -> None:
    conditions=[p['cells']==p['pairs']==32,p['arm_side_rows']==192,p['comparisons']==432,
                p['P6_strict_continuation']=='NOT_MET',p['ineligible_challenges']==['F6-V2','F6-V3','F7-V4'],
                p['no_primary_novelty_promotion'] is True,p['no_A19_A20_activation'] is True,
                p['frozen_expectation_disagreements']==0,not p['failures']]
    if not all(conditions):
        raise Refusal('pilot count, eligibility, decision or authority changed')

def corrected_oracle(raw: dict) -> dict:
    result=copy.deepcopy(raw)
    limits=result.get('limitations',[])
    if limits.count(LEGACY_ERRATUM)!=1:
        raise Refusal('legacy oracle wording differs; no broad automatic replacement')
    result['limitations']=[ORACLE_CORRECTION if x==LEGACY_ERRATUM else x for x in limits]
    return result

def derived(out: Path) -> dict[str, Any]:
    p=read(out/'experiment/pilot_summary.json');o=read(out/'experiment/oracle.json')
    red=read(out/'experiment/redteam.json');t=read(out/'regression/result.json')
    old=read(out/'regression/oracle.json');claims=read(out/'regression/claims.json')
    proto=read(out/'protocol/raw.json');require_pilot(p)
    if o['status']!='PASS' or o['programs']!=32 or o['callables']!=40 or o['checks']!=592 or o['failures']:
        raise Refusal('oracle extension inconsistent')
    if not t['success'] or t['failures'] or t['errors'] or old['status']!='PASS' or claims['status']!='PASS' or proto['status']!='PASS':
        raise Refusal('regression failure')
    return {
      'schema':'codeprobe-p7d-evidence-numbers/1',
      'A17':{'pairs':p['pairs'],'families':len({r['id'].split('-')[0] for r in p['rows']}),
             'arms':3,'side_arm_rows':p['arm_side_rows'],'comparisons':p['comparisons'],
             'ineligible':p['ineligible_challenges'],'incremental_cells':p['incremental_cells'],
             'strict_continuation':p['P6_strict_continuation'],'novelty_promoted':False},
      'A18':{'programs':o['programs'],'families':o['family_count'],'callables':o['callables'],
             'checks':sum(len(r['comparisons']) for r in o['rows']), 'disagreements':len(o['failures']),
             'sources_executed':o['sources_executed']},
      'postpilot':{'checks':red['checks'],'exploratory':True,'family_overlap':red['family_overlap']},
      'regression':{'mode':t['source_mode'],'tests':t['tests'],'failures':t['failures'],
                    'errors':t['errors'],'skips':t['skips'],
                    'legacy_oracle_programs':old['cases'],'legacy_oracle_checks':old['checks'],
                    'legacy_claim_status':claims['status'],'legacy_protocol_tests':proto['summary']['tests'],
                    'legacy_protocol_checks':proto['summary']['checks']},
      'Q07':'NOT_QUALIFIED','full_editorial_pipeline_qualified':False,
      'A19_A20_active':False,'counts_are_overlapping_obligations':True
    }

