    buf=io.StringIO(newline='');writer=csv.writer(buf,lineterminator='\n')
    writer.writerow(['program','expected_callables','checks','all_comparisons_agree'])
    for row in o['rows']:
        writer.writerow([row['id'],len(row['expected']),len(row['comparisons']),all(c.get('actual',c.get('observed'))==c['expected'] for c in row['comparisons'])])
    text(dest/'A18_programs.csv',buf.getvalue())
    text(dest/'NUMBERS.tex','% P7D generated input; editorial integration remains pending.\n'+
         '\\newcommand{\\CPASeventeenPairs}{'+str(numbers['A17']['pairs'])+'}\n'+
         '\\newcommand{\\CPASeventeenDecision}{'+numbers['A17']['strict_continuation'].replace('_','\\_')+'}\n'+
         '\\newcommand{\\CPAEighteenPrograms}{'+str(numbers['A18']['programs'])+'}\n'+
         '\\newcommand{\\CPAEighteenChecks}{'+str(numbers['A18']['checks'])+'}\n')
    summary=f"""# Integrated reproduction evidence\n\nA17: **{numbers['A17']['strict_continuation']}**. All {numbers['A17']['pairs']} pairs are retained. The three ineligible challenges remain visible.\n\nA18: {numbers['A18']['programs']} programs, {numbers['A18']['callables']} callables and {numbers['A18']['checks']} checks; {numbers['A18']['disagreements']} disagreements.\n\nThe {numbers['regression']['mode']} regression ran {numbers['regression']['tests']} tests, with {numbers['regression']['failures']} failures, {numbers['regression']['errors']} errors and {numbers['regression']['skips']} declared skips. Legacy protocol checks are historical-contract regressions; they do not certify current gate semantics by themselves.\n\n"""
